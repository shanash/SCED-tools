def parse_args(argv=None) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Build an offline per-card image-atlas index for "
                    "the Korean langpack, and (--coverage) the authoritative "
                    "Korean image-language coverage report.",
        epilog="Coverage supersedes Korean_report.json for judging whether "
               "Korean content renders Korean art; see " + DOC_POINTER + ".",
    )
    scope = p.add_mutually_exclusive_group()
    scope.add_argument("--source-dir", type=Path, default=None,
                       help="Walk exactly this directory as a single pack "
                            "labelled 'playercards'. Default: the decomposed "
                            "Korean Player Cards directory. Mutually "
                            "exclusive with --packs.")
    scope.add_argument("--packs", default=None,
                       help="Comma-separated subset of "
                            + ",".join(PACKS) + ", or 'all'. Each is "
                            "resolved against --decomposed-root. Mutually "
                            "exclusive with --source-dir.")
    p.add_argument("--decomposed-root", type=Path,
                   default=DEFAULT_DECOMPOSED_ROOT,
                   help="Root the --packs entries are resolved against "
                        "(default: SCED-downloads/decomposed). Relocation / "
                        "test hook only; ignored by --source-dir.")
    p.add_argument("--coverage", action="store_true",
                   help="Two effects: (1) tolerant object resolution — the "
                        "GMNotes (40) and empty-CustomDeck (43) hard exits "
                        "become row anomalies and Custom_PDF objects enter "
                        "scope; (2) emit korean_coverage_report.json + .csv.")
    p.add_argument("--incumbent-report", type=Path, default=None,
                   help="READ the named Korean_report.json to populate "
                        "incumbent_comparison. Never imports, executes or "
                        "writes anything from SCED-downloads/misc/. "
                        "Requires --coverage.")
    p.add_argument("--out-dir", type=Path, default=None,
                   help="Output directory for the index + manifest. Default: "
                        "output/korean-coverage-metric under --coverage, "
                        "else output/korean-player-card-index.")
    p.add_argument("--pretty", action="store_true",
                   help="No-op alias retained for parity (JSON is already "
                        "indent=2). Does not affect CSV or manifest bytes.")
    p.add_argument("--dry-run", action="store_true",
                   help="Compute everything but write no files; return the "
                        "would-be 0/1 exit code.")
    args = p.parse_args(argv)

    # --incumbent-report requires --coverage. argparse has no native
    # "requires" relation, so this post-parse check is what produces exit 2.
    if args.incumbent_report is not None and not args.coverage:
        p.error("--incumbent-report requires --coverage")

    # Resolve the walk scope into an ordered list of (pack, pack_root) pairs.
    if args.packs is not None:
        names = [s.strip() for s in args.packs.split(",") if s.strip()]
        if not names:
            p.error("--packs requires at least one pack name")
        if "all" in names:
            names = list(PACKS)
        unknown = [n for n in names if n not in PACKS]
        if unknown:
            p.error(
                "unknown --packs entries: %s (valid: %s, or 'all')"
                % (",".join(unknown), ",".join(PACKS))
            )
        selected = [n for n in PACKS if n in set(names)]
        root: Path = args.decomposed_root
        args.pack_pairs = [(n, root / PACKS[n]) for n in selected]
        args.single_pack_default = False
    else:
        source_dir = (
            DEFAULT_SOURCE_DIR if args.source_dir is None else args.source_dir
        )
        args.pack_pairs = [(PACK, source_dir)]
        args.single_pack_default = True

    if args.out_dir is None:
        args.out_dir = (
            DEFAULT_OUTPUT_COVERAGE if args.coverage else DEFAULT_OUTPUT
        )
    return args


def _resolve_gmnotes_sidecar(obj: dict, path: Path, pack_root: Path) -> str:
    """Resolve an id from an external ``.gmnotes`` sidecar; "" on miss.

    Lifts korean-image-audit.py:166-201 (the only script that already handles
    both GMNotes shapes) and hardens it with a containment guard the precedent
    lacks: ``GMNotes_path`` is attacker-influenceable data in a file the fork
    syncs from upstream, so a candidate resolving outside the pack root's
    parent is refused rather than read. Candidate order (design §5.3(ii)):

    1. the sibling ``<stem>.gmnotes`` — the one real case in this tree;
    2. ``pack_root.parent / GMNotes_path`` — the measured anchor;
    3. ``pack_root / GMNotes_path`` with the leading pack-root name stripped.
    """
    gm_path = obj.get("GMNotes_path")
    candidates = [path.parent / (path.stem + ".gmnotes")]
    if isinstance(gm_path, str) and gm_path:
        normalized = gm_path.replace("\\", "/")
        candidates.append(pack_root.parent / normalized)
        prefix = pack_root.name + "/"
        if normalized.startswith(prefix):
            candidates.append(pack_root / normalized[len(prefix):])

    try:
        boundary = pack_root.parent.resolve()
    except OSError:
        return ""

    for cand in candidates:
        try:
            resolved = cand.resolve()
        except OSError:
            continue
        if boundary != resolved and boundary not in resolved.parents:
            print(
                f"GMNotes sidecar refused (outside {boundary}): {resolved}",
                file=sys.stderr,
            )
            continue
        try:
            if not resolved.is_file():
                continue
            text = resolved.read_text(encoding="utf-8")
        except OSError:
            continue
        try:
            gm = json.loads(text)
        except (json.JSONDecodeError, ValueError):
            continue
        if isinstance(gm, dict) and gm.get("id") is not None:
            print(
                f"GMNotes resolved from sidecar: {path} -> {resolved.name}",
                file=sys.stderr,
            )
            return str(gm["id"])
    return ""


def _parse_gmnotes_id(
    obj: dict,
    location: str,
    tolerant: bool = False,
    path: Path = None,
    pack_root: Path = None,
) -> tuple:
    """Parse GMNotes (string or dict) and return ``(id, anomaly_code)``.

    Reuses the invariant pattern from build-candidates-index.py.

    Strict mode (the default, and today's behaviour) hard-exits 40 on any of
    the four violation shapes. Tolerant mode (``--coverage``) first attempts
    sidecar resolution and then returns ``("", gmnotes_unresolved)`` instead of
    exiting, so one unparseable object out of thousands cannot abort a
    coverage walk.
    """
    def violation(reason: str) -> tuple:
        if not tolerant:
            print(
                f"GMNotes invariant violation: {reason} at {location} "
                f"(--coverage records this as a row anomaly instead)",
                file=sys.stderr,
            )
            sys.exit(40)
        resolved = ""
        if path is not None and pack_root is not None:
            resolved = _resolve_gmnotes_sidecar(obj, path, pack_root)
        if resolved:
            return resolved, ANOMALY_GMNOTES_SIDECAR_RESOLVED
        print(
            f"GMNotes unresolved ({reason}) at {location}",
            file=sys.stderr,
        )
        return "", ANOMALY_GMNOTES_UNRESOLVED

    raw = obj.get("GMNotes", "")
    if isinstance(raw, dict):
        gm = raw
    elif isinstance(raw, str):
        if not raw.strip():
            return violation("empty GMNotes")
        try:
            gm = json.loads(raw)
        except json.JSONDecodeError:
            return violation("non-JSON GMNotes")
    else:
        return violation("unexpected type")
    if not isinstance(gm, dict) or "id" not in gm:
        return violation("missing 'id' key")
    return str(gm["id"]), ""


def _coerce_int(value, location: str, field: str) -> int:
    """Coerce CustomDeck NumWidth/NumHeight to int (R4 mitigation).

    TTSModManager normalization may emit floats — accept ints/floats convertible
    to int losslessly. Anything else is an invariant violation.
    """
    if isinstance(value, bool):
        # bools are ints in Python; treat as invariant violation explicitly.
        print(
            f"Grid invariant violation: bool value for {field} at {location}",
            file=sys.stderr,
        )
        sys.exit(41)
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        if not math.isfinite(value):
            # NaN / +-Infinity (json.load accepts these tokens) is not coercible
            # to int — fail cleanly with the grid invariant code, not a traceback.
            print(
                f"Grid invariant violation: non-finite {field}={value!r} at {location}",
                file=sys.stderr,
            )
            sys.exit(41)
        coerced = int(value)
        if float(coerced) != value:
            print(
                f"Grid invariant violation: non-integral {field}={value!r} at {location}",
                file=sys.stderr,
            )
            sys.exit(41)
        return coerced
    print(
        f"Grid invariant violation: non-numeric {field}={value!r} at {location}",
        file=sys.stderr,
    )
    sys.exit(41)


def _coerce_card_id(value) -> int | None:
    """Soft-coerce a CardID to int; return None on any invalid value.

    Unlike the grid _coerce_int (hard exit 41), this never exits: CardID is the
    row's own primary key and the inventory philosophy is keep-and-flag, not
    crash (design §5.3). A None result means anomaly=card_id_invalid: the cell
    math and the deckkey_mismatch check are both skipped, the row is kept, and
    the run contributes to exit 1. Invalid = missing / null / bool /
    non-integral float / non-numeric.
    """
    if value is None:
        return None
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, float):
        if not math.isfinite(value):
            # NaN / +-Infinity (json.load accepts these tokens): not a usable
            # CardID — keep-and-flag (return None), never crash on int(nan)/int(inf).
            return None
        coerced = int(value)
        if float(coerced) != value:
            return None
        return coerced
    return None


def classify_host(url: str) -> str:
    """Classify an atlas image URL host as a total enum: R2 | Steam | other.

    Applied independently to face_url and back_url (DRY within this script).

    # TODO(host-classifier-unification): single shared classify_host across
    # this script and extract-korean-atlases.py — see design §3/§5.9
    """
    if R2_HOST_FRAGMENT in url:
        return "R2"
    if STEAM_HOST_FRAGMENT in url:
        return "Steam"
    return "other"


def resolve_image_source(obj: dict, custom_deck_entry) -> tuple:
    """Return ``(url, field_label)`` for the object's FACE image.

    Shape-driven, never guessed: a Custom_PDF carries its image in
    ``CustomPDF.PDFUrl`` and has no CustomDeck at all; a card carries it in the
    selected ``CustomDeck`` entry's ``FaceURL``. ``custom_deck_entry is None``
    is the empty-CustomDeck signal from build_card_record (design §5.3(iii)).
    """
    if obj.get("Name") == "Custom_PDF":
        return (obj.get("CustomPDF") or {}).get("PDFUrl", ""), "CustomPDF.PDFUrl"
    if custom_deck_entry is not None:
        return custom_deck_entry.get("FaceURL", ""), "CustomDeck.FaceURL"
    return "", "none"


def image_language(url: str) -> str:
    """Adapt classify_host()'s three-valued host enum to a language verdict.

    A thin, separately-testable adapter rather than a second classifier, so
    the TODO(host-classifier-unification) path stays open: a future shared
    classifier only has to preserve classify_host's three-valued contract.
    """
    if not url:
        return LANG_UNKNOWN
    return HOST_LANGUAGE.get(classify_host(url), LANG_UNKNOWN)


def unknown_host_label(url: str) -> str:
    """Bucket label for the unknown_breakdown map."""
    if not url:
        return "(absent)"
    try:
        host = urlparse(url).hostname or ""
    except ValueError:
        host = ""
    if not host:
        return "(relative)"
    return host


def derive_unit_key(pack: str, source_file: str, arkham_id: str) -> str:
    """Derive ``<pack>/<unit>`` for the coverage rollup (design §3.5).

    ``campaigns``/``fancampaigns`` use the first path component (the campaign
    directory), falling back to the file stem for objects sitting directly at
    the pack root. ``playercards`` is flat — the directory rule would put
    1,859 of 2,136 objects in one bucket — so it uses the two-digit id prefix
    as a derived ``cycle-NN``. ``unit_key_source`` is emitted on every row so
    a derived cycle bucket is never mistaken for a real directory.

    Separator-normalised at construction via PurePosixPath, never patched
    afterwards, so the value is always '/' and never '\\'.
    """
    if UNIT_KEY_SOURCE.get(pack, "directory") == "id_prefix":
        if re.match(r"^\d{2}\d{3}", arkham_id or ""):
            unit = "cycle-" + arkham_id[:2]
        else:
            unit = "cycle-unknown"
    else:
        parts = PurePosixPath(*Path(source_file).parts).parts
        if len(parts) >= 2:
            unit = parts[0]
        elif parts:
            unit = PurePosixPath(parts[-1]).stem
        else:
            unit = "(root)"
    return str(PurePosixPath(pack) / unit)


def compute_sha256(path: Path) -> str:
    """Compute SHA-256 hex digest of a file's contents."""
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def atomic_write_json(path: Path, data: dict) -> None:
    """Write JSON via .tmp + os.replace for atomicity.

    Uses indent=2, ensure_ascii=False, sort_keys=False to preserve cards order.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    try:
        tmp.write_text(
            json.dumps(data, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
        tmp.replace(path)
    finally:
        # Defensive cleanup if replace failed.
        if tmp.exists():
            try:
                tmp.unlink()
            except OSError:
                pass


def build_card_record(
    path: Path,
    source_dir: Path,
    obj: dict,
    pack: str = PACK,
    tolerant: bool = False,
) -> dict:
    """Parse one decomposed card JSON into a per-card index record.

    ``obj`` is the already-parsed JSON for ``path``; the caller parses each file
    exactly once (and uses the same object to decide whether the file is in
    scope), so this function never re-reads the file.

    Hard exits: 40 (GMNotes), 41 (grid), 43 (empty CustomDeck). 40 and 43 are
    STRICT-mode only — under ``tolerant`` (``--coverage``) both are demoted to
    row anomalies so a coverage walk cannot be aborted by one object.
    Row-level anomalies (kept + flagged): card_id_invalid, multi_deck,
    deckkey_mismatch, cell_out_of_bounds, and (tolerant only)
    gmnotes_sidecar_resolved, gmnotes_unresolved, no_custom_deck.
    """
    location = str(path)
    source_file = str(path.relative_to(source_dir))

    anomalies: list[str] = []

    arkham_id, gmnotes_anomaly = _parse_gmnotes_id(
        obj, location, tolerant=tolerant, path=path, pack_root=source_dir
    )
    if gmnotes_anomaly:
        anomalies.append(gmnotes_anomaly)
    name = obj.get("Nickname", "")
    sideways = bool(obj.get("SidewaysCard", False))

    # Validate CardID (soft — keep-and-flag, never sys.exit).
    card_id = _coerce_card_id(obj.get("CardID"))
    if card_id is None:
        anomalies.append(ANOMALY_CARD_ID_INVALID)

    custom_deck = obj.get("CustomDeck", {})
    if not custom_deck:
        if not tolerant:
            print(
                f"Card invariant violation: empty CustomDeck at {path} "
                f"(--coverage records this as a row anomaly instead)",
                file=sys.stderr,
            )
            sys.exit(43)
        anomalies.append(ANOMALY_NO_CUSTOM_DECK)
        # TOTAL, INERT values — never leave these unbound. The whole
        # deck-derivation block below is skipped, and every downstream
        # dereference (deck_key at the record/CSV/anomaly-detail sites, and
        # entry.get(...) for FaceURL/NumWidth/NumHeight/BackURL/UniqueBack)
        # then works untouched: {}.get(k, d) is d. Leaving them unbound
        # raises UnboundLocalError and writes NO output files at all.
        deck_key = ""
        entry: dict = {}
        custom_deck_entry = None
    else:
        # Select the single deck entry the SAME way the reuse source does,
        # then validate the CardID//100 relationship rather than using it as
        # selector.
        deck_key = next(iter(custom_deck))
        if len(custom_deck) != 1:
            anomalies.append(ANOMALY_MULTI_DECK)
            # Disambiguate by re-selecting the entry whose key ==
            # str(CardID//100).
            if card_id is not None:
                expected_key = str(card_id // 100)
                if expected_key in custom_deck:
                    deck_key = expected_key
        entry = custom_deck[deck_key]
        custom_deck_entry = entry

        # Validate the CardID//100 invariant (skipped when card_id is invalid).
        if card_id is not None:
            expected_key = str(card_id // 100)
            if expected_key != deck_key:
                anomalies.append(ANOMALY_DECKKEY_MISMATCH)

    # FRONT derivation. The FACE image is the verdict driver; for a Custom_PDF
    # it lives in CustomPDF.PDFUrl rather than in a CustomDeck entry, so
    # resolve_image_source() picks by object shape and records which field it
    # used. face_url/face_source therefore always describe the image actually
    # judged — for an ordinary card this is byte-identical to
    # entry.get("FaceURL", "").
    face_url, image_source_field = resolve_image_source(obj, custom_deck_entry)
    nw = _coerce_int(entry.get("NumWidth", 0), location, "NumWidth")
    nh = _coerce_int(entry.get("NumHeight", 0), location, "NumHeight")

    # x/y default to the typed sentinel (None). cell_index is None only when
    # card_id is invalid (no usable CardID).
    face_cell_index: int | None = None
    face_x: int | None = None
    face_y: int | None = None

    if card_id is not None and custom_deck_entry is not None:
        cell = card_id % 100
        face_cell_index = cell
        capacity = nw * nh
        if cell >= capacity:
            anomalies.append(ANOMALY_CELL_OUT_OF_BOUNDS)
            # Keep raw cell_index (informational); x/y stay sentinel.
        else:
            face_x = cell % nw
            face_y = cell // nw

    # BACK derivation: two-branch rule keyed off the authoritative UniqueBack.
    back_url = entry.get("BackURL", "")
    unique_back = bool(entry.get("UniqueBack", False))

    back: dict | None
    if back_url == "":
        # No back at all: all back_* columns empty, JSON back=null.
        back = None
    elif unique_back:
        # Gridded mirror back: mirrors the face grid + cell (incl. sentinel).
        back = {
            "url": back_url,
            "source": classify_host(back_url),
            "num_width": nw,
            "num_height": nh,
            "cell_index": face_cell_index,
            "x": face_x,
            "y": face_y,
            "single_image": False,
        }
    else:
        # Single shared cardback: one whole image, a 1x1 cell at origin.
        back = {
            "url": back_url,
            "source": classify_host(back_url),
            "num_width": 1,
            "num_height": 1,
            "cell_index": 0,
            "x": 0,
            "y": 0,
            "single_image": True,
        }

    # Grid/cell are null — NEVER 0 — when there is no CustomDeck: a 0x0 grid
    # would read as a real grid of capacity zero.
    if custom_deck_entry is None:
        grid_nw: int | None = None
        grid_nh: int | None = None
    else:
        grid_nw = nw
        grid_nh = nh

    record = {
        "name": name,
        "arkham_id": arkham_id,
        "card_id": card_id,
        "deck_key": deck_key,
        "face": {
            "url": face_url,
            "source": classify_host(face_url),
            "num_width": grid_nw,
            "num_height": grid_nh,
            "cell_index": face_cell_index,
            "x": face_x,
            "y": face_y,
        },
        "back": back,
        "unique_back": unique_back,
        "sideways": sideways,
        "pack": pack,
        "image_language": image_language(face_url),
        "image_source_field": image_source_field,
        "unit_key": derive_unit_key(pack, source_file, arkham_id),
        "source_file": source_file,
        "anomaly": ";".join(anomalies),
    }
    return record


def _csv_cell(value) -> str:
    """Render a JSON-side value as a CSV cell (None -> empty string).

    bool renders as "True"/"False" via str() (bool is an int subclass), so no
    special-casing is needed beyond the None -> "" rule.
    """
    if value is None:
        return ""
    return str(value)


