def read_incumbent_report(path: Path, this_report_korean_pct):
    """READ (never import, exec or write) a Korean_report.json for comparison.

    Returns ``(comparison_or_None, ok)``. A missing or malformed file is a
    warning, not a hard exit: one stderr line naming the path and the reason,
    ``incumbent_comparison`` stays null, the run continues and still writes
    both coverage outputs, and the run exits 1.

    The try/except is load-bearing rather than defensive: a bare json.load
    failure happens to exit 1 as well, so without it the documented exit code
    could not distinguish the contract being honoured from an unhandled
    traceback.
    """
    try:
        with path.open(encoding="utf-8") as fh:
            data = json.load(fh)
        if not isinstance(data, dict):
            raise ValueError("top-level JSON value is not an object")
    except (OSError, ValueError) as exc:
        print(
            f"--incumbent-report unreadable: {path} ({exc.__class__.__name__}: "
            f"{exc}); incumbent_comparison left null",
            file=sys.stderr,
        )
        return None, False

    metadata = data.get("metadata")
    if not isinstance(metadata, dict):
        metadata = {}
    content = data.get("content")
    if not isinstance(content, dict):
        content = {}
    # Windows-generated reports key content as 'campaign\\The Dunwich Legacy'.
    # Normalise separators before anything derived from a key is stored.
    normalised_keys = sorted(str(k).replace("\\", "/") for k in content)

    total_found = metadata.get("total_found")
    total_required = metadata.get("total_required")
    if total_found is None and total_required is None:
        incumbent_total = None
    else:
        incumbent_total = f"{total_found} / {total_required}"

    headline_delta = None
    incumbent_pct_value = _parse_percent(metadata.get("overall_completion"))
    if incumbent_pct_value is not None and this_report_korean_pct is not None:
        headline_delta = round(this_report_korean_pct - incumbent_pct_value, 2)

    return {
        "path": str(path),
        "read_only": True,
        "incumbent_last_updated": metadata.get("last_updated"),
        "incumbent_overall_completion": metadata.get("overall_completion"),
        "incumbent_total": incumbent_total,
        "incumbent_content_keys": normalised_keys,
        "this_report_korean_pct": this_report_korean_pct,
        "headline_delta_points": headline_delta,
        "per_unit_comparison": "not attempted",
        "per_unit_comparison_reason": (
            "the incumbent keys content as 'campaign\\The Dunwich Legacy' "
            "(Windows separators, display names); this report keys as "
            "'campaigns/TheDunwichLegacy.2898f6' (decomposed directory names). "
            "Mapping the two requires a name table that does not exist; "
            "inventing a fuzzy match would fabricate precision."
        ),
        "separator_normalisation": (
            "incumbent content keys are read with '\\\\' -> '/' applied before "
            "any comparison"
        ),
    }, True


def _display_source_path(pack_root: Path) -> str:
    """Render a pack root relative to the decomposed tree when it lives there.

    Keeps sources[].path stable and short for the canonical layout (the design
    §3.1 form) while still naming an arbitrary --source-dir honestly.
    """
    try:
        rel = pack_root.resolve().relative_to(DEFAULT_DECOMPOSED_ROOT.resolve())
        return str(PurePosixPath(*rel.parts))
    except (ValueError, OSError):
        return pack_root.as_posix()


def _parse_percent(value):
    """Parse '86.70 %' into 86.7; None on anything unparseable."""
    if isinstance(value, (int, float)) and not isinstance(value, bool):
        return float(value)
    if not isinstance(value, str):
        return None
    match = re.search(r"-?\d+(?:\.\d+)?", value)
    if not match:
        return None
    try:
        return float(match.group(0))
    except ValueError:
        return None


def main(argv=None) -> int:
    args = parse_args(argv)

    out_dir: Path = args.out_dir
    tolerant: bool = args.coverage
    pack_pairs = args.pack_pairs

    for pack, pack_root in pack_pairs:
        if not pack_root.exists():
            label = "--source-dir" if args.single_pack_default else "--packs"
            print(
                f"{label} does not exist: {pack_root} (pack {pack})",
                file=sys.stderr,
            )
            return 43

    records: list[dict] = []
    sources: list[dict] = []
    json_files_scanned = 0
    for pack, pack_root in pack_pairs:
        pack_objects = 0
        for path in sorted(pack_root.rglob("*.json")):
            with path.open(encoding="utf-8") as fh:
                peek = json.load(fh)
            # Skip files lacking both CardID and CustomDeck (not counted).
            # Under --coverage the predicate is widened to admit Custom_PDF
            # guide / campaign-log objects, which carry neither; container
            # JSONs (the pack-level bags) still skip correctly.
            if "CardID" not in peek and "CustomDeck" not in peek:
                if not (tolerant and peek.get("Name") == "Custom_PDF"):
                    continue
            json_files_scanned += 1
            pack_objects += 1
            records.append(
                build_card_record(path, pack_root, peek, pack, tolerant)
            )
        sources.append({
            "pack": pack,
            "path": _display_source_path(pack_root),
            "unit_key_source": UNIT_KEY_SOURCE.get(pack, "directory"),
            "objects": pack_objects,
        })

    # Sort by (pack, arkham_id, card_id, source_file) for deterministic output.
    # card_id can be None (card_id_invalid); sort those last via a typed key.
    # With one pack this is identical to the pre-multi-pack key; `pack` in the
    # leading position is what makes the tuple a total order across packs even
    # if two packs produced the same relative path.
    records.sort(key=lambda r: (
        r["pack"],
        r["arkham_id"],
        (r["card_id"] is None, r["card_id"] or 0),
        r["source_file"],
    ))

    counts = build_counts(records, json_files_scanned)
    anomaly_entries = build_anomaly_list(records)

    drift = counts["json_files_scanned"] != counts["cards_written"]
    if drift:
        print(
            f"Count drift: json_files_scanned={counts['json_files_scanned']} "
            f"!= cards_written={counts['cards_written']}",
            file=sys.stderr,
        )

    warnings_emitted = bool(anomaly_entries) or drift

    if args.single_pack_default:
        print(
            f"Loaded {json_files_scanned} player card files "
            f"from {pack_pairs[0][1]}."
        )
    else:
        breakdown = ", ".join(
            f"{s['pack']} {s['objects']}" for s in sources
        )
        print(
            f"Loaded {json_files_scanned} objects from "
            f"{len(pack_pairs)} packs ({breakdown})."
        )
    print(
        f"Built {len(records)} cards "
        f"(face: R2 {counts['face_source']['R2']} / Steam {counts['face_source']['Steam']} "
        f"/ other {counts['face_source']['other']}; "
        f"back: R2 {counts['back_source']['R2']} / Steam {counts['back_source']['Steam']} "
        f"/ other {counts['back_source']['other']}; anomalies {counts['anomalies']})."
    )
    for entry in anomaly_entries:
        print(
            f"ANOMALY {entry['code']}: card_id={entry['card_id']} "
            f"arkham_id={entry['arkham_id']} source_file={entry['source_file']} "
            f"{entry['detail']}",
            file=sys.stderr,
        )

    generated_at = datetime.now(timezone.utc).isoformat()

    # `source_dir` is kept verbatim (the pack subpath, even when --source-dir
    # overrides it) for backward compatibility; `sources[]` is authoritative in
    # all modes.
    if len(pack_pairs) == 1:
        source_dir_field = PACKS.get(pack_pairs[0][0], SOURCE_SUBPATH)
    else:
        source_dir_field = "(multiple; see sources[])"

    index_doc = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": generated_at,
        "source_dir": source_dir_field,
        "sources": sources,
        "counts": counts,
        "anomalies": anomaly_entries,
        "cards": records,
    }

    coverage_report = None
    if args.coverage:
        coverage_report = build_coverage_report(records, sources, generated_at)
        totals = coverage_report["totals"]
        if args.incumbent_report is not None:
            comparison, ok = read_incumbent_report(
                args.incumbent_report, totals["korean_pct"]
            )
            coverage_report["incumbent_comparison"] = comparison
            if not ok:
                warnings_emitted = True
        pct = totals["korean_pct"]
        pct_text = "n/a (denominator 0)" if pct is None else f"{pct}%"
        print(
            f"Coverage (face image language): korean {totals['korean']} "
            f"/ english {totals['english']} / unknown {totals['unknown']}"
        )
        print(
            f"  headline: {pct_text} Korean (denominator "
            f"{totals['denominator']}, unknown excluded and declared)"
        )
        print(
            "  NOTE: this is far below Korean_report.json's headline BY "
            "DESIGN — that metric counts"
        )
        print(
            "        id presence and never reads an image URL. See "
            + DOC_POINTER + "."
        )
        disagreement = coverage_report["disagreement_with_incumbent"]
        print(
            f"  disagreement with the incumbent metric: "
            f"{disagreement['objects']} objects / "
            f"{disagreement['distinct_ids']} distinct ids"
        )
        multi = coverage_report["multi_owner_ids"]
        print(
            f"  face/back mismatch: {totals['face_back_mismatch']} objects   "
            f"multi-owner ids: {multi['ids_in_multiple_units']} "
            f"({multi['verdict_conflict_count']} with conflicting verdicts)"
        )
        measurable = [
            u for u in coverage_report["units"] if u["korean_pct"] is not None
        ]
        bottom = sorted(
            measurable, key=lambda u: (u["korean_pct"], -u["objects"], u["unit_key"])
        )[:5]
        if bottom:
            print(
                "Bottom 5 units by korean_pct: "
                + " | ".join(
                    f"{u['unit_key']} {u['korean_pct']}% ({u['objects']})"
                    for u in bottom
                )
            )

    if args.dry_run:
        print("(dry-run mode — no files written)")
        return 1 if warnings_emitted else 0

    out_dir.mkdir(parents=True, exist_ok=True)

    json_path = out_dir / "korean_card_index.json"
    csv_path = out_dir / "korean_card_index.csv"
    manifest_path = out_dir / "manifest.json"
    coverage_json_path = out_dir / "korean_coverage_report.json"
    coverage_csv_path = out_dir / "korean_coverage_report.csv"

    atomic_write_json(json_path, index_doc)
    write_csv(csv_path, records)

    verify_paths = [json_path, csv_path]
    outputs = {
        "korean_card_index.json": {"sha256": compute_sha256(json_path)},
        "korean_card_index.csv": {"sha256": compute_sha256(csv_path)},
    }
    if coverage_report is not None:
        atomic_write_json(coverage_json_path, coverage_report)
        write_coverage_csv(coverage_csv_path, coverage_report["units"])
        verify_paths.extend([coverage_json_path, coverage_csv_path])
        outputs["korean_coverage_report.json"] = {
            "sha256": compute_sha256(coverage_json_path)
        }
        outputs["korean_coverage_report.csv"] = {
            "sha256": compute_sha256(coverage_csv_path)
        }

    json_sha = outputs["korean_card_index.json"]["sha256"]
    csv_sha = outputs["korean_card_index.csv"]["sha256"]

    manifest = {
        "schema_version": SCHEMA_VERSION,
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "indexer": {
            "script": INDEXER_SCRIPT,
            "version": SCHEMA_VERSION,
        },
        "mode": "index+coverage" if args.coverage else "index",
        "packs": [pack for pack, _ in pack_pairs],
        "source_dir": source_dir_field,
        "sources": sources,
        "counts": counts,
        "anomalies": anomaly_entries,
        "outputs": outputs,
    }
    atomic_write_json(manifest_path, manifest)

    # Re-read every data output and verify sha256 matches the manifest claim.
    declared = manifest["outputs"]
    for path in verify_paths:
        actual = compute_sha256(path)
        expected = declared[path.name]["sha256"]
        if actual != expected:
            print(
                f"sha256 mismatch on re-read: {path.name} "
                f"declared={expected!r} actual={actual!r}",
                file=sys.stderr,
            )
            return 42

    print(f"Wrote {json_path}  sha256={json_sha[:16]}...")
    print(f"Wrote {csv_path}  sha256={csv_sha[:16]}...")
    if coverage_report is not None:
        print(
            f"Wrote {coverage_json_path}  "
            f"sha256={outputs['korean_coverage_report.json']['sha256'][:16]}..."
        )
        print(
            f"Wrote {coverage_csv_path}  "
            f"sha256={outputs['korean_coverage_report.csv']['sha256'][:16]}..."
        )
    print(f"Wrote {manifest_path}")

    return 1 if warnings_emitted else 0


if __name__ == "__main__":
    sys.exit(main())
