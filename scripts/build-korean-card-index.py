#!/usr/bin/env python3
"""
Build an offline per-card image-atlas index for the Korean langpack, and
(opt-in) the authoritative Korean image-language coverage report.

Reads the decomposed TTS card JSON directly from
``SCED-downloads/decomposed/language-pack/Korean - */`` (approach A2) and emits,
for each object, which atlas image (front + back) it uses and where the card
sits within the atlas grid (``cell_index``, ``x``, ``y``). Deliverable A only:
no image cropping, no network access, no atlas-dimension fetching.

Reading decomposed JSON is what makes the index correct: each file isolates
exactly one deck, so no wrong-deck grid can be joined — unlike the packed
catalog, which mis-joined grids for 3 promo cards.

Coverage mode (``--coverage``) additionally assigns every object an
**image-language verdict derived from the host of the image URL it actually
points at** (R2 -> korean, Steam -> english, anything else -> unknown), rolls
those verdicts up per content unit, and writes ``korean_coverage_report.json``
/ ``.csv``.

SUPERSEDES, for judging whether Korean langpack content renders Korean art:
``SCED-downloads/misc/localization_reports/Korean_report.json`` (generated by
``SCED-downloads/misc/language-pack-completion-stats.py``). That metric decides
coverage by GMNotes-id set membership and reads no image URL, so an object
carrying the right id while pointing at the English Steam host scores as
covered there. It is NOT superseded for its inventory of ids required but
absent from the Korean tree — this script never reads the English base tree.
See ``SCED-tools/docs/korean-coverage-metric.md``.

Output under ``output/korean-player-card-index/`` (index) or
``output/korean-coverage-metric/`` (``--coverage``):
  - korean_card_index.csv        (1 row per card, 23 columns, RFC-4180 quoting)
  - korean_card_index.json       (structured record array + counts + anomalies)
  - korean_coverage_report.json  (--coverage only; per-unit + global rollup)
  - korean_coverage_report.csv   (--coverage only; 1 row per unit, 15 columns)
  - manifest.json                (run metadata, counts, anomalies, sha256)

Usage:
  build-korean-card-index.py
    [--source-dir PATH | --packs LIST] [--decomposed-root PATH]
    [--coverage] [--incumbent-report PATH]
    [--out-dir PATH] [--pretty] [--dry-run]

Exit codes:
  0  OK: no anomalies AND no count-reconciliation drift
  1  warnings: one or more row-level anomalies, OR count drift
     (json_files_scanned != cards_written), OR an unreadable
     --incumbent-report. Non-fatal — outputs still written.
     Exit 1 is the ORDINARY outcome of `--packs all --coverage`: the tree
     carries anomalies that are recorded rather than fatal. Do not read it
     as a failed run, and do not expect any particular anomaly count.
  40 GMNotes invariant violation (missing / empty / non-JSON / missing 'id').
     STRICT MODE ONLY. Under --coverage this is demoted to the row anomaly
     gmnotes_unresolved (or gmnotes_sidecar_resolved when GMNotes_path
     resolves).
  41 grid invariant violation (NumWidth/NumHeight not losslessly int-coercible)
  42 sha256 mismatch on write-back verification
  43 missing source/pack dir, or a card with empty CustomDeck.
     The empty-CustomDeck half is STRICT MODE ONLY. Under --coverage it is
     demoted to the row anomaly no_custom_deck. The missing-dir half is
     unconditional and also fires for a --packs entry whose directory is
     absent.
   2 argparse usage error (e.g. --source-dir with --packs, or
     --incumbent-report without --coverage)
"""
