def test_every_slice_carries_a_sha256_that_matches_disk(tmp_path):
    """§6 step 11: "per-file sha256". §5.11 clause (e) asserts an assembled
    package against these digests, so a recorded digest that does not match the
    file is a package assertion that passes on the wrong bytes."""
    box = make_box(tmp_path, cards=TEN_BY_SEVEN)
    regrid(box, 10, 7, 12, 16, cells=TEN_CELLS)
    _report, manifest = ks.run_slice(box.run_dir, workspace=box.root)

    for entry in manifest["records"]:
        path = slice_path(box, entry["filename"])
        assert len(entry["sha256"]) == 64
        assert entry["sha256"] == kc.sha256_file(path)
        assert entry["bytes"] == os.path.getsize(path)


def test_manifest_describes_exactly_the_directory(tmp_path):
    """Set equality in both directions (SL8). A file in `slices/` the manifest
    does not name is a file that would ship undeclared."""
    box = make_box(tmp_path, cards=TEN_BY_SEVEN)
    regrid(box, 10, 7, 12, 16, cells=TEN_CELLS)
    _report, manifest = ks.run_slice(box.run_dir, workspace=box.root)

    on_disk = set(os.listdir(os.path.join(box.run_dir, ks.SLICES_DIR)))
    on_disk.discard(ks.MANIFEST_NAME)
    assert on_disk == set(r["filename"] for r in manifest["records"])

    stray = slice_path(box, "undeclared.png")
    shutil.copyfile(slice_path(box, manifest["records"][0]["filename"]), stray)
    checks, triggered = ks.verify_emitted(manifest["records"], box.run_dir)
    sl8 = [c for c in checks if c["id"] == "SL8"][0]
    assert sl8["status"] == "fail"
    assert kc.EXIT_RULE_B in triggered


def test_contact_sheet_is_written_and_names_every_slice(tmp_path):
    """The human review surface. It is not gated here -- `slice` is not one of
    §3.2's four gated stages -- but it is the surface the `mask` gate reads, and
    a gallery that omits a slice is a review nobody performed on it."""
    box = make_box(tmp_path, cards=TEN_BY_SEVEN)
    regrid(box, 10, 7, 12, 16, cells=TEN_CELLS)
    report, manifest = ks.run_slice(box.run_dir, workspace=box.root)

    path = os.path.join(box.run_dir, ks.GALLERY_DIR, ks.CONTACT_SHEET_NAME)
    assert os.path.exists(path)
    with open(path, "r", encoding="utf-8") as handle:
        html = handle.read()
    for entry in manifest["records"]:
        assert entry["filename"] in html
        assert str(entry["cell"]) in html
        assert entry["arkham_id"] in html
    # Self-contained but for the sibling PNGs. The atlas URL appears as TEXT --
    # a reviewer has to see which sheet a section came off -- so the assertion is
    # about what the page would FETCH, not about what it prints.
    assert "<script" not in html and "<link" not in html and "@import" not in html
    assert html.count("<img") == len(manifest["records"])
    assert html.count('src="../%s/' % ks.SLICES_DIR) == len(manifest["records"])
    assert report["results"]["contact_sheet"].endswith(ks.CONTACT_SHEET_NAME)


