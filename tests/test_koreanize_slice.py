# -*- coding: utf-8 -*-
"""kz_slice.py -- the `slice` stage (design §6 step 11, §5.4).

WHAT §6 STEP 11 ASKS THIS SUITE TO COVER, LITERALLY
    "`test_koreanize_slice.py` covers `(1,1)`, `(10,7)` and a non-integral
     division that must refuse."

    Those three are the whole point of the stage's existence, because they are
    exactly what `slice-atlases.py` could not do. That script carries
    `EXPECTED_SHEET_DIMS` at `:48-53` -- three hand-recorded tuples -- and
    `CELL_W, CELL_H = 750, 1050` at `:46`, so a `(1,1)` sheet is a `KeyError`, a
    `(10,7)` sheet is a `KeyError`, and a sheet whose pixels do not divide by its
    grid is a silent off-by-N crop that produces plausible-looking cards.
    `test_one_by_one_*`, `test_ten_by_seven_*` and `test_non_integral_*` below
    are the three cases R-A is mitigated by, and `test_module_declares_no_cell_
    size_table` is what stops the table growing back.

WHY EVERY CASE BUILDS ITS OWN PIXELS
    §5.9 marks corpus-dependent tests `needs_golden` and skips them when the
    2.1 GB fixture is absent -- so a suite resting on it has zero passing
    evidence on any machine without the corpus, which is the position
    `test_koreanize_checkers.py`'s header describes W1 being rescued from. Every
    image below is generated by `kz_slice.synth_atlas`, which paints a DIFFERENT
    colour per cell: on a uniform sheet every crop is identical and no assertion
    here could tell a correct slice from an off-by-one one.

WHY THE SANDBOX AND NOT A HAND-WRITTEN run_dir
    `slice` reads a hash-pinned `scenario.json`, `atlas-inventory.json` and
    `card-text-en.json`, and the pin means a hand-written config is a config that
    stops validating the day `kz_config` gains a field. `koreanize_sandbox.Sandbox`
    already drives the real `init` to produce all three; `regrid()` below then
    rewrites the ONE thing `init` cannot produce offline -- a measured atlas --
    and re-pins. So the inputs are `init`'s own, not this file's idea of them.
"""

import json
import os
import shutil
import subprocess
import sys

import pytest

import kz_common as kc
import kz_slice as ks
import kz_config as kz

from tests.koreanize_sandbox import EN_FACE, Sandbox

SLICE_PY = os.path.join(kc.PACKAGE_DIR, "kz_slice.py")


# ---------------------------------------------------------------------------
# 0. The fixture: a real init run whose one atlas has been measured for us
# ---------------------------------------------------------------------------

def regrid(box, num_width, num_height, cell_w, cell_h, pixels=None, cells=None):
    """Give the sandbox's single English atlas a MEASURED geometry.

    `init` records `pixels: null` for any sheet it could not fetch, and the
    sandbox runs it with `download_atlases=False` because no test may reach the
    network -- so the one input `slice` cannot get from the real `init` here is
    the measurement. This plants it, consistently, in all three artifacts that
    carry it:

      * `<run_dir>/assets/<sha256>.png`, where `init` would have put the download
      * `atlas-inventory.json`, the record `slice` confirms against
      * `scenario.json`, re-pinned -- `config_sha256` is what stops a hand-edit
        silently retargeting the tool (`kz_config.validate`), and a fixture that
        skipped the re-pin would be testing the pin instead of the stage

    and it recomputes each object's `row`/`col` in `card-text-en.json`, because
    those are `divmod(cell, num_width)` and moving the grid moves them.

    `pixels` overrides the sheet's recorded dims WITHOUT changing the file, which
    is the only way to build the non-integral case: `synth_atlas` can only draw a
    sheet that divides.

    `cells` reassigns which cell each object sits in, and it exists because the
    sandbox's cards are authored against a 7x4 `CustomDeck` -- `init` itself
    refuses a `CardID` whose cell falls outside the grid it was written with
    (`kz_init.check_geometry`), so a 10x7 fixture cannot state its cells up front
    without making `init` refuse before this helper is ever reached. Assigning
    them AFTER `init` is what lets the same sandbox carry a 70-cell sheet, and
    `card_id` is recomputed with the cell so TTS's own `deck_key*100 + cell`
    round-trip still holds.
    """
    run_dir = box.run_dir
    # When `pixels` is given the SHEET is drawn at those dims and the grid is
    # declared independently of them -- which is the whole non-integral case:
    # `synth_atlas` can only ever draw a sheet that divides by the grid it is
    # given, so a fixture that drew `num_width x num_height` cells and then
    # relabelled the record would refuse at 14 (the file no longer matches the
    # measurement) before the integrality assertion was ever reached.
    if pixels:
        atlas_path = ks.synth_atlas(os.path.join(run_dir, "atlas-src.png"),
                                    1, 1, pixels[0], pixels[1])
    else:
        atlas_path = ks.synth_atlas(os.path.join(run_dir, "atlas-src.png"),
                                    num_width, num_height, cell_w, cell_h)
    digest = kc.sha256_file(atlas_path)
    assets = os.path.join(run_dir, "assets")
    if not os.path.isdir(assets):
        os.makedirs(assets)
    shutil.copyfile(atlas_path, os.path.join(assets, "%s.png" % digest))
    os.unlink(atlas_path)

    measured = list(pixels) if pixels else [num_width * cell_w, num_height * cell_h]
    record = {
        "atlas_id": digest[:16], "side": "face", "english_url": EN_FACE,
        "local": os.path.join("<run_dir>", "assets", "%s.png" % digest),
        "grid": {"num_width": num_width, "num_height": num_height},
        "pixels": measured,
        "cell_pixels": ([measured[0] // num_width, measured[1] // num_height]
                        if not (measured[0] % num_width or measured[1] % num_height)
                        else None),
        "bytes": os.path.getsize(os.path.join(assets, "%s.png" % digest)),
        "sha256": digest,
        "cells_used": 1, "packs": [],
        "single_card": bool(num_width == 1 and num_height == 1),
    }

    inventory_path = os.path.join(run_dir, "atlas-inventory.json")
    inventory = _read(inventory_path)
    inventory["atlases"] = [record]
    _write(inventory_path, inventory)

    scenario_path = os.path.join(run_dir, "scenario.json")
    cfg = _read(scenario_path)
    cfg["atlases"] = [record]
    cfg["config_sha256"] = kz.compute_config_sha256(cfg)
    _write(scenario_path, cfg)

    en_path = os.path.join(run_dir, "card-text-en.json")
    en_doc = _read(en_path)
    for obj in en_doc["objects"]:
        if obj.get("cell") is None:
            continue
        if cells is not None and obj.get("arkham_id") in cells:
            obj["cell"] = cells[obj["arkham_id"]]
            obj["card_id"] = int(obj["deck_key"]) * 100 + obj["cell"]
        obj["num_width"] = num_width
        obj["num_height"] = num_height
        obj["row"], obj["col"] = divmod(obj["cell"], num_width)
    _write(en_path, en_doc)

    box.cfg = cfg
    return record


def _read(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def _write(path, data):
    with open(path, "w", encoding="utf-8") as handle:
        json.dump(data, handle, indent=2, ensure_ascii=False)
        handle.write("\n")


def make_box(tmp_path, cards):
    """A sandbox with `cards` and no donors, through the real `init`.

    No donors and no `source()` run: `slice`'s only predecessor is `init`
    (`kz_config.PREDECESSORS`), and a fixture that ran more of the chain than the
    stage depends on would fail for reasons that are not this stage's.
    """
    box = Sandbox(tmp_path).build(cards=cards, donors={})
    box.init()
    return box


def atlas_file(box):
    inventory = _read(os.path.join(box.run_dir, "atlas-inventory.json"))
    digest = inventory["atlases"][0]["sha256"]
    return os.path.join(box.run_dir, "assets", "%s.png" % digest)


def slice_path(box, name):
    return os.path.join(box.run_dir, ks.SLICES_DIR, name)


