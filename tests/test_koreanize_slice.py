# 3. (1,1) -- Woods of the Black Goat's shape. A COPY, not a crop.
# ---------------------------------------------------------------------------

def test_one_by_one_atlas_is_copied_byte_for_byte(tmp_path):
    """§5.4: "`single_card` atlases produce a copy, not a crop, and are recorded
    as such."

    Both halves are asserted, because either alone is satisfiable by the wrong
    implementation: a full-sheet `crop()` produces identical PIXELS and different
    BYTES, and a manifest can say `copy` about a re-encode. The byte identity is
    what keeps a Pillow upgrade out of §5.8's byte-exact golden comparison.
    """
    box = make_box(tmp_path, cards=[("111111", "01001", 10000)])
    record = regrid(box, 1, 1, 24, 32)

    report, manifest = ks.run_slice(box.run_dir, workspace=box.root)

    assert report["exit_code"] == kc.EXIT_OK, report["checks"]
    assert report["counts"]["atlases_single_card"] == 1
    assert report["counts"]["slices_copied"] == 1
    assert report["counts"]["slices_cropped"] == 0

    entry = manifest["records"][0]
    assert entry["operation"] == "copy"
    assert entry["cell_pixels"] == [24, 32]
    assert entry["sha256"] == record["sha256"]
    with open(slice_path(box, entry["filename"]), "rb") as emitted:
        with open(atlas_file(box), "rb") as source:
            assert emitted.read() == source.read()


def test_one_by_one_cell_pixels_are_the_whole_sheet(tmp_path):
    """The arithmetic, isolated from the emission: on a (1,1) sheet the derived
    cell IS the sheet, which is the case a constant table gets wrong by
    construction."""
    box = make_box(tmp_path, cards=[("111111", "01001", 10000)])
    record = regrid(box, 1, 1, 40, 55)
    assert ks.cell_pixels_for(record, measured=(40, 55)) == (40, 55)


# ---------------------------------------------------------------------------
# 4. (10,7) -- Labyrinths' shape. A crop, from the RIGHT cell.
# ---------------------------------------------------------------------------

#: The sandbox's own cards, authored against the 7x4 `CustomDeck` its `_card`
#: helper writes, so `init` accepts them; `regrid(cells=...)` then moves them
#: onto the 10x7 sheet. Cell 69 is deliberately the LAST cell of that grid, so
#: the crop box reaches the sheet's far corner exactly and an off-by-one in
#: either axis leaves the sheet instead of passing quietly.
TEN_BY_SEVEN = [("111111", "01001", 10001),
                ("222222", "01002", 10002),
                ("333333", "01003", 10003)]
TEN_CELLS = {"01001": 1, "01002": 10, "01003": 69}


def test_ten_by_seven_derives_the_cell_and_crops_each_card(tmp_path):
    """The 70-cell sheet no constant table in the repository describes.

    The last card is deliberately cell 69 -- the final cell of a 10x7 grid -- so
    the crop box reaches the sheet's far corner exactly. An off-by-one in either
    axis leaves the sheet and refuses at 20 rather than passing quietly.
    """
    box = make_box(tmp_path, cards=TEN_BY_SEVEN)
    regrid(box, 10, 7, 12, 16, cells=TEN_CELLS)

    report, manifest = ks.run_slice(box.run_dir, workspace=box.root)

    assert report["exit_code"] == kc.EXIT_OK, report["checks"]
    assert report["counts"]["slices"] == 3
    assert report["counts"]["slices_cropped"] == 3
    assert report["counts"]["slices_copied"] == 0
    assert report["counts"]["atlases_single_card"] == 0

    cells = dict((r["arkham_id"], (r["cell"], r["row"], r["col"], tuple(r["box"])))
                 for r in manifest["records"])
    assert cells["01001"] == (1, 0, 1, (12, 0, 24, 16))
    assert cells["01002"] == (10, 1, 0, (0, 16, 12, 32))
    assert cells["01003"] == (69, 6, 9, (108, 96, 120, 112))
    for entry in manifest["records"]:
        assert entry["cell_pixels"] == [12, 16]


def test_ten_by_seven_slices_carry_the_pixels_of_their_own_cell(tmp_path):
    """THE case that catches a wrong-cell crop, which no dimension check can.

    Every emitted slice is compared against the crop taken independently from the
    source sheet at the box the manifest declares -- and `synth_atlas` paints a
    different colour per cell, so a slice cut one cell over is different bytes
    rather than the same picture. The three slices are also asserted PAIRWISE
    DISTINCT, because on a uniform sheet the comparison above passes for every
    permutation and establishes nothing.
    """
    from PIL import Image

    box = make_box(tmp_path, cards=TEN_BY_SEVEN)
    regrid(box, 10, 7, 12, 16, cells=TEN_CELLS)
    _report, manifest = ks.run_slice(box.run_dir, workspace=box.root)

    digests = set()
    with Image.open(atlas_file(box)) as sheet:
        rgba = sheet.convert("RGBA")
        for entry in manifest["records"]:
            expected = rgba.crop(tuple(entry["box"]))
            with Image.open(slice_path(box, entry["filename"])) as emitted:
                assert emitted.size == (12, 16)
                assert emitted.convert("RGBA").tobytes() == expected.tobytes(), \
                    entry["filename"]
            digests.add(entry["sha256"])
    assert len(digests) == 3, "the cells are indistinguishable, so this proves nothing"


def test_ten_by_seven_cell_pixels_are_derived_not_looked_up(tmp_path):
    """`(10,7)` at the reference cell size, through the arithmetic alone.

    750x1050 is Midwinter's cell and 10x7 is Carnevale's grid (§3.4), so this is
    the pair a reintroduced table would be written from. It is asserted here
    without drawing a 55 MP sheet, because the derivation does not need pixels.
    """
    record = {"english_url": "https://example.invalid/a.png",
              "grid": {"num_width": 10, "num_height": 7},
              "pixels": [7500, 7350], "cell_pixels": [750, 1050],
              "single_card": False}
    assert ks.cell_pixels_for(record, measured=(7500, 7350)) == (750, 1050)


