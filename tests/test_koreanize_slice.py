# 8. The path guard -- writes stay inside <run_dir>
# ---------------------------------------------------------------------------

def _tree(root):
    out = {}
    for dirpath, _dirnames, filenames in os.walk(root):
        for name in filenames:
            path = os.path.join(dirpath, name)
            out[path] = os.path.getmtime(path)
    return out


def test_nothing_outside_the_run_dir_is_touched(tmp_path):
    """§4.1's `writes outside <run_dir>: no` column, asserted on the filesystem.

    The subject is the sandbox's whole SCED-downloads tree, because that is what
    a mis-scoped write root would reach -- and it is a directory `slice` has no
    business opening even for reading.
    """
    box = make_box(tmp_path, cards=TEN_BY_SEVEN)
    regrid(box, 10, 7, 12, 16, cells=TEN_CELLS)
    downloads = os.path.join(box.root, "SCED-downloads")
    before = _tree(downloads)

    ks.run_slice(box.run_dir, workspace=box.root)

    assert _tree(downloads) == before


