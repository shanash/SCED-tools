# 5. The non-integral division -- it must refuse
# ---------------------------------------------------------------------------

def test_non_integral_division_refuses_at_precondition(tmp_path):
    """§6 step 11's third required case.

    A 100x100 sheet declared as a 7x4 grid has NO cell size: 100 % 7 == 2 and
    100 % 4 == 0, so one axis divides and the other does not. Exit 13 and not 20:
    nothing has been sliced wrongly, the INPUT cannot be sliced at all -- which
    is the same class and the same code `kz_init.measure_atlases` refuses the
    identical fact with, deliberately down to the message string.
    """
    box = make_box(tmp_path, cards=[("111111", "01001", 10001)])
    regrid(box, 7, 4, 10, 10, pixels=[100, 100])

    with pytest.raises(kc.KzRefusal) as excinfo:
        ks.run_slice(box.run_dir, workspace=box.root)

    assert excinfo.value.code == kc.EXIT_PRECONDITION
    assert "do not divide by its grid" in excinfo.value.message
    assert "100 % 7 = 2" in excinfo.value.detail


def test_non_integral_division_writes_nothing(tmp_path):
    """"Nothing was written" is the whole value of a precondition refusal.

    The assertion is on the filesystem and not on the message: a stage that
    refused after emitting half a directory would report the same code and leave
    a partial `slices/` for the next run to consume.
    """
    box = make_box(tmp_path, cards=[("111111", "01001", 10001)])
    regrid(box, 7, 4, 10, 10, pixels=[100, 100])

    with pytest.raises(kc.KzRefusal):
        ks.run_slice(box.run_dir, workspace=box.root)

    assert not os.path.exists(os.path.join(box.run_dir, ks.SLICES_DIR))
    assert not os.path.exists(os.path.join(box.run_dir, ks.GALLERY_DIR))
    assert not os.path.exists(kc.report_path(box.run_dir, "slice", "build"))


@pytest.mark.parametrize("pixels,grid", [
    ([100, 100], (7, 4)),      # neither axis divides cleanly on width
    ([100, 100], (2, 3)),      # width divides, height does not
    ([101, 100], (1, 1)),      # a (1,1) sheet always divides -- see below
])
def test_non_integral_cases(pixels, grid):
    """The refusal is per axis, not per sheet.

    The third row is the one that earns its place: on a `(1,1)` grid EVERY
    dimension divides, so the integrality assertion is vacuous there and the
    `single_card` path can never reach it. Stating that here stops a future
    "optimise: skip the check for single_card" edit from reading as a change in
    behaviour when it is not.
    """
    record = {"english_url": "https://example.invalid/a.png",
              "grid": {"num_width": grid[0], "num_height": grid[1]},
              "pixels": pixels, "cell_pixels": None,
              "single_card": bool(grid == (1, 1))}
    if grid == (1, 1):
        assert ks.cell_pixels_for(record) == tuple(pixels)
        return
    with pytest.raises(kc.KzRefusal) as excinfo:
        ks.cell_pixels_for(record)
    assert excinfo.value.code == kc.EXIT_PRECONDITION


