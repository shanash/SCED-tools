def test_verify_only_catches_a_slice_replaced_after_the_build(tmp_path):
    """The re-read is not ceremony: it is the only thing that sees a file
    replaced between the write and the read. `--verify-only` reads the records
    from the manifest ON DISK rather than from a fresh plan, because verifying a
    plan against itself establishes nothing about the files a previous run
    left."""
    box = make_box(tmp_path, cards=TEN_BY_SEVEN)
    regrid(box, 10, 7, 12, 16, cells=TEN_CELLS)
    _report, manifest = ks.run_slice(box.run_dir, workspace=box.root)

    clean, _ = ks.run_slice(box.run_dir, mode="verify-only", workspace=box.root)
    assert clean["exit_code"] == kc.EXIT_OK, clean["checks"]

    victim = slice_path(box, manifest["records"][0]["filename"])
    with open(victim, "wb") as handle:
        handle.write(b"\x89PNG not really")

    tampered, _ = ks.run_slice(box.run_dir, mode="verify-only", workspace=box.root)
    assert tampered["exit_code"] == kc.EXIT_RULE_B
    sl7 = [c for c in tampered["checks"] if c["id"] == "SL7"][0]
    assert sl7["status"] == "fail"
    assert manifest["records"][0]["filename"] in " ".join(sl7["detail"])


