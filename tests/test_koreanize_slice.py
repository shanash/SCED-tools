# 2. The constant table is gone, and `norm()` is not
# ---------------------------------------------------------------------------

def test_module_declares_no_cell_size_table():
    """R-A's structural mitigation, asserted on the source text.

    §5.4: "`slice-atlases.py:48-53`'s `EXPECTED_SHEET_DIMS` constant disappears."
    A cell size that can be looked up is a cell size somebody will look up, and
    the failure mode is silent -- a table hit for the wrong sheet crops plausible
    cards from the wrong offsets. The literal figures are searched for because
    they are the ones that would be reintroduced: 750x1050 is Midwinter's cell.
    """
    import ast

    with open(SLICE_PY, "r", encoding="utf-8") as handle:
        tree = ast.parse(handle.read(), filename=SLICE_PY)

    # Parsed and not grepped, because the module's own header QUOTES the legacy
    # constants in order to explain their deletion. A text scan cannot tell a
    # citation from a declaration, so it would either fail on the prose or be
    # weakened until it passed on a real one.
    assigned, literals = set(), set()
    for node in tree.body:
        targets = []
        if isinstance(node, ast.Assign):
            targets = node.targets
        elif isinstance(node, ast.AnnAssign):
            targets = [node.target]
        else:
            continue
        for target in targets:
            if isinstance(target, ast.Name):
                assigned.add(target.id)
        for inner in ast.walk(node):
            if isinstance(inner, ast.Constant) and isinstance(inner.value, int):
                literals.add(inner.value)

    for banned in ("EXPECTED_SHEET_DIMS", "SHEET_DIMS", "CELL_W", "CELL_H",
                   "CELL_PIXELS", "CELL_SIZE"):
        assert banned not in assigned, "%s is back as a module constant" % banned

    # And no MODULE-LEVEL constant may carry the reference cell size as a literal
    # pair: 750x1050 is Midwinter's cell and is what a reintroduced table would
    # hold. Scoped to module level deliberately -- `--selftest integrality` plants
    # [750, 1050] as a fault fixture, and that is the opposite of a lookup table.
    assert not (750 in literals and 1050 in literals)


def test_norm_is_the_legacy_normalisation():
    """`slice-atlases.py:56-57`, kept. The suite asserts it against the regex
    form because "kept" has to be checkable: if these diverge, every file in
    `images-ko/assets/` becomes unreachable at once and with no diagnostic."""
    import re
    legacy = lambda s: re.sub(r"[^a-zA-Z0-9]", "", s).lower()  # noqa: E731
    for sample in ("https://steamusercontent-a.akamaihd.net/ugc/24078/C570E6/",
                   "", "Ab_9-/.", "MiXeD CaSe", "%20", "ünïcödé"):
        assert ks.norm(sample) == legacy(sample), sample


def test_url_stem_filenames_prefix_match_their_url():
    """The property the read-only tier's mapping rests on: `images-ko/assets/`
    names each download after its URL with the punctuation stripped, so the
    on-disk name is `norm(url)` plus an extension."""
    url = "https://steamusercontent-a.akamaihd.net/ugc/24078/C570E6/"
    assert ks.norm(url + ".png").startswith(ks.norm(url))
    assert ks.norm(ks.norm(url) + ".png").startswith(ks.norm(url))


